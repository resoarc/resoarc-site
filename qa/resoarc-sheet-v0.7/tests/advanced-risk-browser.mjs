import { chromium } from 'playwright-core';
import ExcelJS from 'exceljs';
import {mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import assert from 'node:assert/strict';

const dir=join(process.cwd(),'tests','qa-artifacts');
await mkdir(dir,{recursive:true});
const input=join(dir,'advanced-risk.xlsx');
const book=new ExcelJS.Workbook();
const sheet=book.addWorksheet('要注意',{views:[{state:'frozen',xSplit:1,ySplit:1}]});
sheet.mergeCells('A1:B1');
sheet.getCell('A1').value='テスト帳票';
sheet.getCell('A2').value=20;
sheet.getCell('B2').value=30;
sheet.getCell('C2').value={formula:'A2+B2',result:50};
sheet.getCell('B3').dataValidation={type:'list',allowBlank:false,formulae:['"A,B,C"']};
sheet.getCell('A4').value={text:'ResoArc',hyperlink:'https://example.org'};
sheet.addConditionalFormatting({ref:'A2:B2',rules:[{type:'expression',formulae:['A2>10'],style:{fill:{type:'pattern',pattern:'solid',bgColor:{argb:'FFFF0000'}}}}]});
await book.xlsx.writeFile(input);
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--no-first-run','--disable-extensions']});
try{
 const page=await browser.newPage({viewport:{width:1380,height:900},acceptDownloads:true});
 const dialogs=[],errors=[],downloads=[];
 page.on('dialog',async d=>{dialogs.push(d.message());if(dialogs.length===1)await d.dismiss();else await d.accept();});
 page.on('download',d=>downloads.push(d.suggestedFilename()));
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.RESOARC_BASE_URL||'http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 await page.locator('input[accept=".xlsx,.csv"]').setInputFiles(input);
 await page.waitForTimeout(2700);
 await page.getByRole('tab',{name:'ファイル'}).click();
 assert.match(await page.locator('.notice-line').innerText(),/要注意/);
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.waitForTimeout(1600);
 const status=(await page.locator('.statusbar').innerText());
 console.log('CANCEL STATUS',status.slice(0,200));
 console.log('FIRST DIALOG',dialogs[0]?.slice(0,560));
 assert.match(status,/保存を中止/);
 assert.equal(downloads.length,0);
 const dlPromise=page.waitForEvent('download',{timeout:25000});
 await page.getByRole('button',{name:'保存',exact:true}).click();
 const dl=await dlPromise;
 const saved=join(dir,'advanced-risk-output.xlsx');
 await dl.saveAs(saved);
 const out=new ExcelJS.Workbook();await out.xlsx.readFile(saved);
 assert.equal(out.getWorksheet('要注意').getCell('C2').value?.formula,'A2+B2');
 assert.ok(dialogs.length>=2);
 const reportPromise=page.waitForEvent('download',{timeout:15000});
 await page.getByRole('tab',{name:'校閲'}).click();
 await page.getByRole('button',{name:'互換性監査'}).click();
 const reportFile=await reportPromise;
 const reportPath=join(dir,'advanced-risk-audit.json');
 await reportFile.saveAs(reportPath);
 const audit=JSON.parse(await (await import('node:fs/promises')).readFile(reportPath,'utf8'));
 assert.equal(audit.format,'resoarc-sheet-compat-report-1');
 assert.ok(audit.losses.some(x=>x.id==='conditional'));
 assert.ok(!JSON.stringify(audit).includes('テスト帳票'));
 assert.deepEqual(errors,[]);
 console.log('PASS: risk detected, cancel blocks download, explicit opt-in downloads');
 console.log(JSON.stringify({dialogs:dialogs.map(x=>x.slice(0,500)),downloads,output:saved},null,2));
}catch(e){console.log('FAILED',e.stack);process.exitCode=1}finally{await browser.close();}
