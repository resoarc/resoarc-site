import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {join} from 'node:path';
const root=join(process.cwd(),'tests','qa-artifacts');
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--no-first-run','--disable-extensions']});
let failed=false;
try{
 const page=await browser.newPage({viewport:{width:1380,height:840},acceptDownloads:true});
 page.setDefaultTimeout(6500);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())});
 await page.goto(process.env.RESOARC_BASE_URL||'http://127.0.0.1:5180/',{waitUntil:'networkidle'});
 const name=page.getByRole('textbox',{name:'名前ボックス'}),formula=page.getByRole('textbox',{name:'数式バー'});
 await name.fill('C3');await name.press('Enter');
 await page.locator('.statusbar').click();
 await page.keyboard.press('F2');
 assert.equal(await formula.evaluate(el=>document.activeElement===el),true,'F2 should focus formula bar');
 await formula.fill('2345.5');await formula.press('Enter');
 await page.locator('.statusbar').click();
 await page.keyboard.press('Control+1');
 const dialog=page.getByRole('dialog',{name:'セルの書式設定'});
 await dialog.waitFor({state:'visible'});
 await dialog.getByLabel('分類').selectOption('#,##0.00');
 await dialog.getByLabel('フォント',{exact:true}).selectOption('Arial');
 await dialog.getByLabel('サイズ').selectOption('14');
 await dialog.getByLabel('太字').check();
 await dialog.getByLabel('横位置').selectOption('center');
 await dialog.getByRole('button',{name:'適用'}).click();
 await dialog.waitFor({state:'hidden'});
 await page.getByRole('tab',{name:'ファイル'}).click();
 const event=page.waitForEvent('download',{timeout:16000});
 await page.getByRole('button',{name:'保存',exact:true}).click();
 const dl=await event;
 const dest=join(root,'keyboard-format-v06.xlsx');
 await dl.saveAs(dest);
 const book=new ExcelJS.Workbook();await book.xlsx.readFile(dest);
 const cell=book.worksheets[0].getCell('C3');
 assert.equal(cell.value,2345.5);
 assert.equal(cell.font?.bold,true);
 assert.equal(cell.font?.size,14);
 assert.equal(cell.font?.name,'Arial');
 assert.equal(cell.numFmt,'#,##0.00');
 assert.equal(cell.alignment?.horizontal,'center');
 assert.deepEqual(errors,[]);
 console.log('KEYBOARD_FORMAT_PASS',JSON.stringify({value:cell.value,numFmt:cell.numFmt,font:cell.font,align:cell.alignment?.horizontal,errors}));
}catch(e){failed=true;console.log('KEYBOARD_FORMAT_FAIL',e.stack)}finally{await browser.close()}if(failed)process.exitCode=1;
