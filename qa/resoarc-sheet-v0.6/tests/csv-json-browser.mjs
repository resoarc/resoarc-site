import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {writeFile,readFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
const dir=join(process.cwd(),'tests','qa-artifacts');
await mkdir(dir,{recursive:true});
const csv=join(dir,'input-csv.csv');
await writeFile(csv,'品名,数量,備考\r\n鉛筆,2,確認\r\nノート,5,良好\r\n','utf8');
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--no-first-run','--disable-extensions']});
try{
 const page=await browser.newPage({viewport:{width:1380,height:900},acceptDownloads:true});
 const errors=[];page.on('dialog',d=>d.accept());page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto(process.env.RESOARC_BASE_URL || 'http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 await page.locator('input[accept=".xlsx,.csv"]').setInputFiles(csv);
 await page.waitForTimeout(3500);
 console.log('IMPORT STATUS',(await page.locator('.statusbar').innerText()).slice(0,140));
 await page.getByRole('tab',{name:'ファイル'}).click();
 const backupPromise=page.waitForEvent('download',{timeout:15000});
 await page.getByRole('button',{name:'バックアップ',exact:true}).click();
 const backup=await backupPromise;
 const jsonFile=join(dir,'csv-backup.resoarc.json');
 await backup.saveAs(jsonFile);
 const obj=JSON.parse(await readFile(jsonFile,'utf8'));
 assert.equal(obj.format,'resoarc-fortune-1');
 assert.ok(obj.sheets.length);
 console.log('CSV DATA',JSON.stringify(obj.sheets[0].data?.slice(0,3).map(row=>row?.slice(0,3))).slice(0,600));
 const csvPromise=page.waitForEvent('download',{timeout:15000});
 await page.getByRole('button',{name:'CSV保存'}).click();
 const csvDownload=await csvPromise;
 const result=join(dir,'csv-result.csv');
 await csvDownload.saveAs(result);
 const saved=await readFile(result,'utf8');
 console.log('CSV OUTPUT',JSON.stringify(saved.slice(0,250)));
 assert.ok(saved.includes('鉛筆')&&saved.includes('ノート'));
 await page.getByRole('button',{name:'新規'}).click();
 await page.locator('input[accept=".json"]').setInputFiles(jsonFile);
 await page.waitForTimeout(1700);
 const restored=await page.getByRole('textbox',{name:'ワークブック名'}).inputValue();
 assert.equal(restored,'input-csv');
 const resultPromise=page.waitForEvent('download',{timeout:15000});
 await page.getByRole('button',{name:'バックアップ',exact:true}).click();
 const restoredBackup=await resultPromise;
 const restoredFile=join(dir,'csv-restored.resoarc.json');
 await restoredBackup.saveAs(restoredFile);
 const resultObj=JSON.parse(await readFile(restoredFile,'utf8'));
 assert.equal(resultObj.sheets[0]?.data?.[1]?.[0]?.v,'鉛筆');
 assert.deepEqual(errors,[]);
 console.log('PASS: CSV open/export + JSON restore');
}catch(e){console.error('FAILED',e.stack);process.exitCode=1}finally{await browser.close()}